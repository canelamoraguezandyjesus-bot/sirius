def _temporalidad(
    valid_from: str | None = "2026-01-01T00:00:00Z",
    valid_to: str | None = None,
    occurred_at: str | None = None,
    recorded_at: str = "2026-01-01T00:00:00Z",
) -> dict[str, str | None]:
    return {
        "valid_from": valid_from,
        "valid_to": valid_to,
        "occurred_at": occurred_at,
        "recorded_at": recorded_at,
    }


def _item(
    item_id: str,
    kind: str,
    project_id: str,
    text: str,
    *,
    entity_ids: list[str] | None = None,
    polaridad: str = "AFIRMATIVA",
    condicion: str | None = None,
    confirmacion: str = "CONFIRMADA",
    validez: str = "VIGENTE",
    disponibilidad: str = "DISPONIBLE",
    sensibilidad: str = "ORDINARIA",
    temporalidad: dict[str, Any] | None = None,
    ambito: str = "PROYECTO",
    autoridad: str = "ACTO_EXPLICITO_USUARIO",
    no_usar_como_memoria: bool = False,
    no_consolidable: bool = False,
    criticidad: dict[str, Any] | None = None,
    procedencia: list[str] | None = None,
    traza: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "id": item_id,
        "kind": kind,
        "project_id": project_id,
        "entity_ids": entity_ids or [],
        "text": text,
        "polaridad": polaridad,
        "condicion": condicion,
        "confirmacion": confirmacion,
        "validez": validez,
        "disponibilidad": disponibilidad,
        "sensibilidad": sensibilidad,
        "temporalidad": temporalidad or _temporalidad(),
        "ambito": ambito,
        "autoridad": autoridad,
        "no_usar_como_memoria": no_usar_como_memoria,
        "no_consolidable": no_consolidable,
        "criticidad": criticidad,
        "procedencia": procedencia or [],
        "traza": traza or [],
    }


def _crit(razon: str, fuente: str, regla: str, nivel: str = "CRITICO") -> dict[str, str]:
    """B04 §6: toda marca lleva nivel, razón, fuente y regla aprobada."""
    return {"nivel": nivel, "razon": razon, "fuente": fuente, "regla": regla}


