def construir_referencias(casos: dict[str, Any]) -> dict[str, Any]:
    refs = []
    for caso in casos["nivel_1"]:
        refs.append(
            {
                "caso": caso["id"],
                "identificador_canonico": caso["identificador_canonico"],
                "congelada_por": "B04 v1.0 APROBADO §17 y §17.1",
                "modificable": False,
                "elegibles": caso["candidatos_elegibles"],
                "prohibidos": caso["candidatos_prohibidos"],
                "resultado_esperado": caso["resultado_esperado"],
                "orden_esperado": caso["orden_esperado"],
                "tipo_orden": (
                    "CONJUNTO"
                    if caso["orden_esperado"] is None
                    else ("VACIO" if not caso["orden_esperado"] else "ORDEN_TOTAL")
                ),
                "etapa_esperada": caso["etapa_esperada"],
                "parada_esperada": caso["parada_esperada"],
                "cardinalidad": caso["cardinalidad"],
                "fallo_observable": caso["fallo_observable"],
            }
        )
    return {
        "documento": "Referencias congeladas del benchmark de ADR-002",
        "version": CORPUS_VERSION,
        "estado": "PROPUESTO",
        "regla": (
            "Una referencia de nivel 1 no cambia nunca desde aquí. "
            "Prohibido cambiar el esperado tras observar la salida (RED-004, PDP-CA-02)."
        ),
        "conteos": {"referencias_nivel_1": len(refs)},
        "referencias_nivel_1": refs,
    }


def _volcar(ruta: Path, datos: dict[str, Any]) -> int:
    texto = json.dumps(datos, ensure_ascii=False, indent=1, sort_keys=False) + "\n"
    ruta.write_text(texto, encoding="utf-8")
    return len(texto.encode("utf-8"))


def main() -> None:
    corpus = construir_corpus()
    casos = construir_casos()
    referencias = construir_referencias(casos)
    for nombre, datos in (
        (f"corpus_v0_{CORPUS_VERSION.split('.')[1]}.json", corpus),
        (f"cases_v0_{CORPUS_VERSION.split('.')[1]}.json", casos),
        (f"references_v0_{CORPUS_VERSION.split('.')[1]}.json", referencias),
    ):
        n = _volcar(AQUI / nombre, datos)
        print(f"{nombre}: {n} bytes")


if __name__ == "__main__":
    main()
